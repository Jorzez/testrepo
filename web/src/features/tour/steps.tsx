/* Шаги обучения по интерфейсу: что подсветить, в каком разделе, что сказать
   и что подготовить. Тексты повторяют docs/web-ui.md простыми словами;
   шаги про правку видят редактор и администратор, про администрирование —
   только администратор. Порядок — как разделы в боковой панели. */

export interface TourContext {
  catalog: ReturnType<typeof useCatalog> & Pick<ReturnType<typeof useCheckForm>, "checkForm" | "setCheckForm">;
  auth: ReturnType<typeof useAuth>;
  /** Обучение ещё идёт: ответ, пришедший после выхода из него, форму пользователя не трогает. */
  active: () => boolean;
}

export interface Step {
  id: string;
  title: string;
  body: ReactNode | ((ctx: TourContext) => ReactNode);
  /** Раздел, в котором показывается шаг; без него — остаёмся в текущем. */
  section?: Section;
  /** CSS-селектор подсвечиваемого элемента; без него карточка по центру экрана. */
  target?: string;
  /** Предпочтительное место карточки относительно элемента. */
  place?: "right" | "left" | "bottom" | "top";
  /** Элемент, нажатие на который открывает блок шага: он подсвечивается с подписью, и шаг
      ждёт, пока пользователь сам на него нажмёт (стрелка вправо нажимает за него — через prepare). */
  via?: { target: string; hint: string };
  /** Блок ещё готовится (идёт проверка): ждать его дольше обычного и показывать busy. */
  pending?: () => boolean;
  /** Шаг про боковую панель: держать её раскрытой. */
  side?: boolean;
  /** Кому показывать: редактору и выше либо только администратору. Без поля — всем. */
  role?: "editor" | "admin";
  /** Подготовка перед показом: открыть панель, запустить проверку примера. */
  prepare?: (ctx: TourContext) => Promise<void> | void;
  /** Что показывать, пока идёт подготовка. */
  busy?: string;
  /** Уборка при уходе с шага в любую сторону. */
  after?: (ctx: TourContext) => void;
}


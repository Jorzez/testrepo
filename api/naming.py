"""Нормализация имён атрибутов.

Вынесено в отдельный модуль, потому что этим пользуются и агент (при
сопоставлении ответа модели со словарём), и каталог (чтобы не дать
завести второй узел :CheckTarget, отличающийся только пробелом).
"""

import re


def normalize_name(name: str) -> str:
    """Каноническая форма имени атрибута для сравнения.

    «Срок исполнения», «срок-исполнения» и «срок_исполнения» дают один ключ.
    """
    text = str(name).replace(" ", " ").strip().lower().replace("ё", "е")
    text = re.sub(r"[\s\-]+", "_", text)
    text = re.sub(r"_+", "_", text)
    return text.strip("_")
